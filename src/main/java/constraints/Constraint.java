package constraints;

import org.graffiti.graph.Node;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.atomic.AtomicLong;

/**
 * Base class of all constraints: the constrained nodes and the settings every constraint has (priority, switch,
 * origin, group, deactivation). Subclasses add the parameters of their {@link ConstraintKind}.
 *
 * @author Niklas Gröne
 */
public abstract class Constraint {
    private static final AtomicLong ID_GENERATOR = new AtomicLong(0);
    private final List<Node> nodes;
    private final long id;

    /** True for constraints generated by the layout pipeline; false for constraints the user made. */
    private boolean automatic;

    /** -Dcblayout.feasPriority=class: rank the feasibility guard uses instead of age (higher survives); 0 = unranked. */
    private int rank;

    /** Which constraint wins when constraints contradict each other, see {@link ConstraintConflicts}. */
    private Priority priority = Priority.NORMAL;

    /** False: the user switched the constraint off; it stays in the store but no solve applies it. */
    private boolean enabled = true;

    /** Set by {@link ConstraintConflicts} while the constraint contradicts constraints that rank above it; else null. */
    private Deactivation deactivation;

    /** Which template instance made the constraint (and where in it), or null for one made directly. */
    private ConstraintOrigin origin;

    /** The structure of a layout step the constraint belongs to (a star, the sides of a process, ...), or null. */
    private ConstraintGroup group;

    public Constraint(List<Node> nodes)
    {
        // A copy: callers pass fixed-size lists (Arrays.asList), and removeNode() must be able to shrink it.
        this.nodes = new ArrayList<>(nodes);
        this.id = ID_GENERATOR.getAndIncrement();
    }

    /** What the constraint does (one value per button of the "Constraints" tab). */
    public abstract ConstraintKind getKind();

    /** Fewest nodes the constraint needs; {@link #removeNode(Node)} reports the constraint as void below it. */
    public int getMinNodes() {
        return 2;
    }

    public List<Node> getNodes() {
        return nodes;
    }

    public long getId() {
        return id;
    }

    /** Removes a deleted node; returns true if the constraint is void now (too few nodes left) and should go. */
    public boolean removeNode(Node n){
        this.nodes.remove(n);
        return this.nodes.size() < getMinNodes();
    }

    /**
     * Puts {@code copy} in the place of {@code n}, with everything the constraint keeps for {@code n}: a layout took
     * {@code n} out of the graph for some steps and inserted {@code copy} for it.
     */
    public void replaceNode(Node n, Node copy) {
        int i = nodes.indexOf(n);
        if (i >= 0) nodes.set(i, copy);
    }

    /** The entry of {@code n} in {@code map} under the key {@code copy}, at the same place in the iteration order. */
    protected static <V> void replaceKey(Map<Node, V> map, Node n, Node copy) {
        if (!map.containsKey(n)) return;
        Map<Node, V> entries = new LinkedHashMap<>(map);
        map.clear();
        for (Map.Entry<Node, V> e : entries.entrySet()) map.put(e.getKey() == n ? copy : e.getKey(), e.getValue());
    }

    @Override
    public String toString()
    {
        return "[id=" + id + ", nodes=" + nodes + "]";
    }


    public boolean isAutomatic() {
        return automatic;
    }

    public void setAutomatic(boolean automatic) {
        this.automatic = automatic;
    }

    /** -Dcblayout.feasPriority=class: rank of an automatic constraint in the SBGN feasibility guard (higher survives). */
    public int getRank() {
        return rank;
    }

    public void setRank(int rank) {
        this.rank = rank;
    }

    public Priority getPriority() {
        return priority;
    }

    public void setPriority(Priority priority) {
        this.priority = priority == null ? Priority.NORMAL : priority;
    }

    /**
     * False if the user switched the constraint off, or if it belongs to a template instance (or a part of one) that
     * is switched off as a whole. Solves, the resolver and the lists use this effective state.
     */
    public boolean isEnabled() {
        return enabled && (origin == null || origin.isSwitchedOn());
    }

    /**
     * The constraint's own switch, whatever the switch of its template instance says: switching an instance off and
     * on again restores exactly these individual decisions.
     */
    public boolean isSwitchedOnItself() {
        return enabled;
    }

    /** Sets the constraint's own switch (see {@link #isSwitchedOnItself()}). */
    public void setEnabled(boolean enabled) {
        this.enabled = enabled;
        if (!enabled) deactivation = null;
    }

    /** The template instance that made the constraint, or null. */
    public ConstraintOrigin getOrigin() {
        return origin;
    }

    public void setOrigin(ConstraintOrigin origin) {
        this.origin = origin;
    }

    /** The structure of a layout step the constraint belongs to, or null (see {@link ConstraintGroup}). */
    public ConstraintGroup getGroup() {
        return group;
    }

    /** Set by {@link ConstraintGroup#add}; call that instead. */
    void setGroup(ConstraintGroup group) {
        this.group = group;
    }

    /** Why the last solve did not apply the constraint, or null if it did (or the user switched it off). */
    public Deactivation getDeactivation() {
        return deactivation;
    }

    void setDeactivation(Deactivation deactivation) {
        this.deactivation = deactivation;
    }

    /** True if solves apply the constraint: switched on and not deactivated by a contradiction. */
    public boolean isActive() {
        return isEnabled() && deactivation == null;
    }
}
