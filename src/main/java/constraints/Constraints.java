package constraints;

import org.graffiti.graph.Graph;
import org.graffiti.graph.Node;

import java.util.ArrayList;
import java.util.List;

/**
 * A constraint store: the constraints of one graph in the order they were added, with typed views and the operations
 * the GUI and the layouts use to keep it in step with the graph.
 * @author Niklas Gröne
 */

public class Constraints {

    private ArrayList<Constraint> constraints;

    public Constraints() {
        constraints = new ArrayList<>();
    }

    public void addConstraint(Constraint constraint) {
        constraints.add(constraint);
    }

    public void clear() {
        constraints.clear();
    }

    public ArrayList<Constraint> getAllConstraints() {
        return constraints;
    }

    public List<HorizontalConstraint> getHorizontalConstraints()
    {
        return getConstraints(HorizontalConstraint.class);
    }

    public List<VerticalConstraint> getVerticalConstraints()
    {
        return getConstraints(VerticalConstraint.class);
    }

    public List<SeparationConstraintGraph> getSeparationConstraints()
    {
        return getConstraints(SeparationConstraintGraph.class);
    }

    public List<DistributionConstraintGraph> getDistributionConstraints()
    {
        return getConstraints(DistributionConstraintGraph.class);
    }

    /** All constraints of the given class (subclasses included), in the order they were added. */
    public <T extends Constraint> List<T> getConstraints(Class<T> type)
    {
        List<T> l = new ArrayList<>();
        for (Constraint constraint : constraints)
        {
            if (type.isInstance(constraint)) l.add(type.cast(constraint));
        }
        return l;
    }

    public void removeConstraint(Constraint constraint)
    {
        this.constraints.remove(constraint);

    }

    /**
     * The constraints the user made (not generated by a pipeline step) whose nodes are all in {@code g}, in a new list.
     * Setting up or resetting an SBGN layout run keeps these instead of starting from an empty list.
     */
    public static Constraints userConstraintsOf(Constraints old, Graph g) {
        Constraints kept = new Constraints();
        if (old == null || g == null) return kept;
        for (Constraint c : old.getAllConstraints()) {
            if (isUserConstraintOn(c, g)) kept.addConstraint(c);
        }
        return kept;
    }

    /**
     * In-place form of {@link #userConstraintsOf}: removes the constraints a layout step generated and those with a node
     * outside {@code g}, keeps the user's (and template) constraints on {@code g} in their order. The store object stays
     * the same, so everything that refers to it (the lists, the conflict log, a running applier) sees the result.
     *
     * @return the removed constraints
     */
    public List<Constraint> retainUserConstraintsOf(Graph g) {
        List<Constraint> removed = new ArrayList<>();
        for (Constraint c : constraints) {
            if (g == null || !isUserConstraintOn(c, g)) removed.add(c);
        }
        constraints.removeAll(removed);
        return removed;
    }

    private static boolean isUserConstraintOn(Constraint c, Graph g) {
        if (c.isAutomatic() || c.getNodes() == null) return false;
        boolean inGraph = true;
        for (Node n : c.getNodes()) inGraph &= g.containsNode(n);
        return inGraph;
    }

    /** {@link #userConstraintsOf} without the constraints no solve applies ({@link Constraint#isActive()}). */
    public static Constraints activeUserConstraintsOf(Constraints old, Graph g) {
        Constraints kept = new Constraints();
        for (Constraint c : userConstraintsOf(old, g).getAllConstraints()) if (c.isActive()) kept.addConstraint(c);
        return kept;
    }

    /** Takes a deleted node out of the constraints; returns the constraints that became void and were removed. */
    public List<Constraint> removeNode(Node n){
        ArrayList<Constraint> removeConstraints = new ArrayList<>();
        for (Constraint constraint : constraints) {
            if (!constraint.getNodes().contains(n)) continue;
            if (constraint.removeNode(n)) {
                removeConstraints.add(constraint);
            }
        }
        for (Constraint constraint : removeConstraints) {
            constraints.remove(constraint);
        }
        return removeConstraints;
    }

}
